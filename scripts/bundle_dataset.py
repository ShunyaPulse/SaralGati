"""
SaralGati - Dataset Bundler for Kaggle GPU Runner
Compresses the downloaded dataset.jsonl and embeds it *inside* the Kaggle runner
script (train_unsloth_lora.py) as a self-contained base64 payload.

Why embed instead of shipping a sibling file: `kaggle kernels push` uploads only
the code file named in kernel-metadata.json, so dataset_payload.py and
dataset.jsonl never reach the Kaggle container. A sibling import fails with
"No module named 'dataset_payload'" and the run silently trains on six seed
samples. A standalone dataset_payload.py is still written for notebook use.
"""

import os
import sys
import gzip
import base64

# Marker line inside train_unsloth_lora.py that gets replaced with the payload.
EMBEDDED_MARKER = 'EMBEDDED_DATASET_B64 = ""'


def _encode(raw_bytes):
    return base64.b64encode(gzip.compress(raw_bytes)).decode("ascii")


def _write_payload_module(b64_str, dest_dir):
    """Legacy standalone module, kept for notebook / local runs."""
    dest_file = os.path.join(dest_dir, "dataset_payload.py")
    code = (
        "# Auto-generated by CI pipeline for Kaggle GPU autonomous training\n"
        "import gzip\n"
        "import base64\n\n"
        f'_COMPRESSED_DATA = b"""{b64_str}"""\n\n'
        "def get_dataset_lines():\n"
        '    raw = gzip.decompress(base64.b64decode(_COMPRESSED_DATA)).decode("utf-8")\n'
        "    return [line for line in raw.splitlines() if line.strip()]\n"
    )
    os.makedirs(dest_dir, exist_ok=True)
    with open(dest_file, "w", encoding="utf-8") as f:
        f.write(code)
    return dest_file


def _embed_in_runner(b64_str, dest_dir):
    """Replace the marker in the copied runner so Kaggle's single file carries data."""
    script_path = os.path.join(dest_dir, "train_unsloth_lora.py")
    if not os.path.exists(script_path):
        print(f"⚠️ {script_path} not found; run the copy step before bundling.")
        return None

    with open(script_path, "r", encoding="utf-8") as f:
        source = f.read()

    if EMBEDDED_MARKER not in source:
        print(f"⚠️ Marker {EMBEDDED_MARKER!r} missing from {script_path}; payload not embedded.")
        return None

    with open(script_path, "w", encoding="utf-8") as f:
        f.write(source.replace(EMBEDDED_MARKER, f'EMBEDDED_DATASET_B64 = "{b64_str}"', 1))
    return script_path


def bundle():
    dataset_file = sys.argv[1] if len(sys.argv) > 1 else "dataset.jsonl"
    dest_dir = sys.argv[2] if len(sys.argv) > 2 else "kaggle_push"

    if not os.path.exists(dataset_file) or os.path.getsize(dataset_file) == 0:
        print(f"⚠️ Dataset file '{dataset_file}' not found or empty; skipping payload generation.")
        return

    with open(dataset_file, "rb") as f:
        raw_bytes = f.read()

    line_count = len([line for line in raw_bytes.split(b"\n") if line.strip()])
    b64_str = _encode(raw_bytes)

    payload_module = _write_payload_module(b64_str, dest_dir)
    runner = _embed_in_runner(b64_str, dest_dir)

    print(f"✅ Bundled {line_count} verified training rows ({len(raw_bytes)} bytes -> {len(b64_str)} bytes compressed).")
    print(f"   • wrote {payload_module}")
    if runner:
        print(f"   • embedded the payload into {runner} (the file Kaggle actually runs)")
    else:
        print("   • ⚠️ payload was NOT embedded in the runner; the Kaggle run would fall back to seed data.")


if __name__ == "__main__":
    bundle()
