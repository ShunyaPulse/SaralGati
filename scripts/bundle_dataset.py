"""
SaralGati - Dataset Bundler for Kaggle GPU Runner
Compresses downloaded dataset.jsonl into a self-contained Python module (dataset_payload.py)
for seamless, zero-network, zero-secret loading inside the Kaggle GPU container.
"""

import os
import sys
import gzip
import base64

def bundle():
    dataset_file = sys.argv[1] if len(sys.argv) > 1 else "dataset.jsonl"
    dest_dir = sys.argv[2] if len(sys.argv) > 2 else "kaggle_push"
    dest_file = os.path.join(dest_dir, "dataset_payload.py")

    if not os.path.exists(dataset_file) or os.path.getsize(dataset_file) == 0:
        print(f"⚠️ Dataset file '{dataset_file}' not found or empty; skipping payload generation.")
        return

    with open(dataset_file, "rb") as f:
        raw_bytes = f.read()

    line_count = len([l for l in raw_bytes.split(b"\n") if l.strip()])
    compressed = gzip.compress(raw_bytes)
    b64_str = base64.b64encode(compressed).decode("ascii")

    code = f'''# Auto-generated by CI pipeline for Kaggle GPU autonomous training
import gzip
import base64

_COMPRESSED_DATA = b"""{b64_str}"""

def get_dataset_lines():
    raw = gzip.decompress(base64.b64decode(_COMPRESSED_DATA)).decode("utf-8")
    return [l for l in raw.split("\\n") if l.strip()]
'''

    os.makedirs(dest_dir, exist_ok=True)
    with open(dest_file, "w", encoding="utf-8") as f:
        f.write(code)

    print(f"✅ Bundled {line_count} verified training rows ({len(raw_bytes)} bytes -> {len(b64_str)} bytes compressed) into {dest_file}.")

if __name__ == "__main__":
    bundle()

